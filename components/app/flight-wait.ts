const PREF = /^(東京都|北海道|(?:京都|大阪)府|.{2,3}県)/;

/**
 * 入れた住所の都道府県。都道府県から書いてあればそれ、無ければ書き出しの市区町村の名前が1つの都道府県にだけあるとき、その都道府県
 * （「桐生市織姫町1-1」→ 群馬県。「府中市…」のように2つ以上の都道府県にある名前・読めない住所は null）
 */
export function prefOfLabel(label: string): string | null {
  // 住所の検索と同じく、貼り付けた住所の「日本、」・郵便番号・「住所：」などを外して読む
  const s = pastedAddress(label)
    .normalize("NFKC")
    .replace(/^〒?\s*\d{3}-?\d{4}\s*/, "")
    .replace(/^地番\s*/, "")
    .replace(/\s+/g, "");
  const m = s.match(PREF);
  if (m && PREF_VIEW[m[1]]) return m[1];
  // 郡の名前（「吾川郡いの町」）は市区町村の表に無いので外して見る
  const t = s.replace(/^[^都道府県市区町村]{1,6}?郡(?=.)/, "");
  const prefs = new Set<string>();
  for (const [pref, codes] of Object.entries(MUNI_CODES)) {
    for (const name of Object.values(codes)) {
      const city = name.split(/\s+/)[0];
      if ([...city].length >= 2 && t.startsWith(city)) prefs.add(pref);
    }
  }
  return prefs.size === 1 ? [...prefs][0] : null;
}

/** 調べている間に向かう上空（地図の中心とズーム）。都道府県が読めなければ null（日本の上空のまま、どこかへ寄らない） */
export function waitViewOf(label: string): { center: [number, number]; zoom: number } | null {
  const pref = prefOfLabel(label);
  const v = pref ? PREF_VIEW[pref] : undefined;
  return v ? { center: [v[0], v[1]], zoom: v[2] } : null;
}
