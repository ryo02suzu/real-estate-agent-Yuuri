// 役所の窓口で道路種別を確認するときのメモ。持ち物・聞くこと・FAX／メールの依頼文

/** 窓口へ持っていくもの */
export const BRING = [
  "住宅地図の写し（物件に印をつける）",
  "公図の写しと地番（登記簿で確認）",
  "現地の写真（前面道路の幅・側溝・隅切りが分かるもの）",
];

/** 窓口で聞くこと */
export const ASK = [
  "前面道路の建築基準法上の種別（42条1項○号／2項／43条2項 など）",
  "2項道路なら、後退（セットバック）の位置と距離、中心線が確定しているか",
  "位置指定道路なら、指定番号・指定年月日と指定図面の写しがもらえるか",
  "道路の幅員（認定幅員と現況幅員）と、道路の境界が確定しているか",
  "市道（公道）か私道か。私道なら所有者と通行・掘削の承諾の要否",
];

/** FAX・メールで照会するときの依頼文 */
export function buildInquiryText(address: string, dept: string): string {
  return [
    `${dept} 御中`,
    "",
    "いつもお世話になっております。下記の土地の前面道路について、建築基準法上の道路種別をご教示ください。",
    "",
    `所在地：${address}`,
    "地番：",
    "",
    "確認したい事項",
    ...ASK.map((a, i) => `${i + 1}. ${a}`),
    "",
    "住宅地図・公図の写しを添付します。",
    "お手数をおかけしますが、よろしくお願いいたします。",
    "",
    "会社名：",
    "担当者：",
    "電話：",
  ].join("\n");
}
