// 県のサイトの決まり：リンクは原則自由（報告は要らない）。岡山県のホームページへのリンクだと分かるようにし、フレームの中に取りこまない。
// まだ：市が扱う7市は調べている途中（data/chugoku.ts の調査中の一覧）。県が扱う市町村も、市町村が出している地図（市町村道の地図など）と市町村の窓口は調べている途中。
import type { Contact, Municipality } from "../municipalities";

const pref = "岡山県" as const;

/** 県の決まり（県「建築基準法等に関するよくある質問・回答」・「確認申請等の相談窓口と担当エリア」） */
const PREF_NOTE =
  "道路種別（2項道路など）は、県民局の建設部 管理課 建築指導班の窓口で確かめられる。道路の位置が分かる地図などを窓口に持って行くか、FAX などで問い合わせる（県「建築基準法等に関するよくある質問・回答」）。窓口へ行くときは、あらかじめ連絡する（県「確認申請等の相談窓口と担当エリア」）。幅員4m以上の国道・県道・市町村道は、原則として交差点から交差点までの全長で幅員が4m以上あれば1項1号（同じ資料）。";

/** 県民局の建設部 管理課 建築指導班（電話・場所は県「確認申請等の相談窓口と担当エリア」。備中の FAX は「備中県民局電話番号一覧」の建築指導班の欄） */
const OFFICE = {
  bizen: { dept: "岡山県 備前県民局 建設部 管理課 建築指導班（岡山市北区弓之町6-1）", phone: "086-233-9847" },
  bicchu: { dept: "岡山県 備中県民局 建設部 管理課 建築指導班（倉敷市羽島1083）", phone: "086-434-7160", fax: "086-423-4043" },
  mimasaka: { dept: "岡山県 美作県民局 建設部 管理課 建築指導班（津山市山下53）", phone: "0868-23-1260" },
} as const;
type Office = keyof typeof OFFICE;

const SHORT = (o: Office) => OFFICE[o].dept.replace("岡山県 ", "").replace(/（.*$/, "");

const desk = (office: Office): Contact => ({ ...OFFICE[office], note: PREF_NOTE });

/** 県が扱う市町村（都市計画区域あり）。道路種別の地図はネットに無いので、県民局の窓口で確かめる。whole は都市計画区域が全域の町 */
const prefTown = (name: string, code: string, office: Office, whole = false): Municipality => ({
  pref,
  name,
  codes: [code],
  coverage: "none",
  maps: [],
  contact: desk(office),
  note: `県が扱う市町村（建築確認と道路の判定は${SHORT(office)}。県「確認申請等の相談窓口と担当エリア」）。県の道路種別の地図はネットに見つからなかった。道路種別は県民局の窓口で確かめる（地図を持って行くか、FAX などで問い合わせる）。${whole ? "" : `${name}の一部は都市計画区域の外（国の令和7年都市計画現況調査の都市別一覧）。`}${name}が出している地図（市町村道の地図など）は調べている途中。`,
});

/** 都市計画区域の無い市町村（国の令和7年都市計画現況調査の都市別一覧に無い） */
const outsideTown = (name: string, code: string, office: Office): Municipality => ({
  pref,
  name,
  codes: [code],
  coverage: "outside",
  maps: [],
  contact: desk(office),
  note: `全域が都市計画区域外（国の令和7年都市計画現況調査の都市別一覧に${name}の都市計画区域は無い）。県は「都市計画区域外の場合、法第43条の接道義務はありませんので、法第42条第2項道路等はありません」と書く（県「建築基準法等に関するよくある質問・回答」）。建築のことは${SHORT(office)}が受け持つ（県「確認申請等の相談窓口と担当エリア」）。`,
});

