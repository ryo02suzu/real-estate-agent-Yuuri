import type { Contact, Municipality } from "../municipalities";

const pref = "山口県" as const;

/** 県の決まり（県「指定道路図及び指定道路調書の閲覧」） */
const PREF_NOTE =
  "指定道路図と指定道路調書を、土木建築事務所で閲覧できる（平日 8:30〜17:00。県「指定道路図及び指定道路調書の閲覧」）。調査の済んでいない道路や誤記がありうるので、載っている情報は必ず建築住宅課の建築技術職員に確かめるよう、県が求めている。行く前に、建築技術職員がいるかを電話で確かめる。";

/** 土木建築事務所の建築住宅課（電話・場所は県「建築基準法に係る所管土木建築事務所の一覧」） */
const OFFICE = {
  yanai: { dept: "山口県 柳井土木建築事務所 建築住宅課（柳井市南町3丁目9番3号 山口県柳井総合庁舎4階）", phone: "0820-22-0397" },
  shunan: { dept: "山口県 周南土木建築事務所 建築住宅課（周南市毛利町2-38 山口県周南総合庁舎6階）", phone: "0834-33-6475" },
  ube: { dept: "山口県 宇部土木建築事務所 建築住宅課（美祢市大嶺町東分3449-5 山口県美祢合同庁舎1階 美祢支所）", phone: "0837-52-1660" },
} as const;
type Office = keyof typeof OFFICE;

const SHORT = (o: Office) => OFFICE[o].dept.replace("山口県 ", "").replace(/（.*$/, "");

/** via は、受け持ちの事務所を別の事務所が兼ねているときの注（県の一覧の書き方） */
const desk = (office: Office, via?: string): Contact => ({
  ...OFFICE[office],
  hours: "平日 8:30〜17:00（指定道路図の閲覧の時間）",
  note: `${via ? `${via}。` : ""}${PREF_NOTE}`,
});

/** 県が扱う市町（都市計画区域あり）。道路種別の地図はネットに無いので、土木建築事務所で確かめる。whole は都市計画区域が全域の町 */
const prefTown = (name: string, code: string, office: Office, opt: { whole?: boolean; via?: string } = {}): Municipality => ({
  pref,
  name,
  codes: [code],
  coverage: "none",
  maps: [],
  contact: desk(office, opt.via),
  note: `県が扱う市町（建築確認と道路の判定は${SHORT(office)}${opt.via ? `。${opt.via}` : ""}。県「建築基準法に係る所管土木建築事務所の一覧」）。県の道路種別の地図はネットに見つからなかった。土木建築事務所で指定道路図・指定道路調書を閲覧し、建築住宅課の職員に確かめる。${opt.whole ? "" : `${name}の一部は都市計画区域の外（国の令和7年都市計画現況調査の都市別一覧）。`}${name}が出している地図（市町道の地図など）は調べている途中。`,
});

/** 都市計画区域の無い町（国の令和7年都市計画現況調査の都市別一覧に無い） */
const outsideTown = (name: string, code: string, office: Office, via?: string): Municipality => ({
  pref,
  name,
  codes: [code],
  coverage: "outside",
  maps: [],
  contact: desk(office, via),
  note: `全域が都市計画区域外（国の令和7年都市計画現況調査の都市別一覧に${name}の都市計画区域は無い）。建築基準法の接道の決まり（43条）は、都市計画区域・準都市計画区域の中でかかる。建築のことは${SHORT(office)}が受け持つ${via ? `（${via}）` : ""}（県「建築基準法に係る所管土木建築事務所の一覧」）。`,
});

