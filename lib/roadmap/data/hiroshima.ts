import type { Contact, MapLink, Municipality } from "../municipalities";

const pref = "広島県" as const;

/** 県の決まり（県の「指定道路図」ご利用上の注意・「『指定道路図及び指定道路調書』の閲覧について」） */
const PREF_NOTE =
  "県のネットの指定道路図（参考図）のことは、電話・FAX・メールでは答えない決まりで、建設事務所の建築課の窓口で確かめる（県の「指定道路図」ご利用上の注意）。窓口では、指定道路図と指定道路調書を閲覧できる（閲覧申請書を出して承認を受ける。平日 9:00〜12:00・13:00〜16:30。県「『指定道路図及び指定道路調書』の閲覧について」）。";

/** 建設事務所の建築課（電話は県「県内の建築確認申請・省エネ適判の受付窓口について」の表。西部の FAX・メールは西部建設事務所「建築課」のページ。場所は閲覧のページ） */
const OFFICE = {
  seibu: { dept: "広島県 西部建設事務所 建築課（広島市南区比治山本町）", phone: "082-250-8158", fax: "082-255-3010", email: "djwkenchiku@pref.hiroshima.lg.jp" },
  tobu: { dept: "広島県 東部建設事務所 建築課（福山市三吉町一丁目）", phone: "084-921-1572" },
  hokubu: { dept: "広島県 北部建設事務所 建築課（三次市十日市東四丁目）", phone: "0824-63-5209" },
} as const;
type Office = keyof typeof OFFICE;

const SHORT = (o: Office) => OFFICE[o].dept.replace("広島県 ", "").replace(/（.*$/, "");

const desk = (office: Office): Contact => ({
  ...OFFICE[office],
  hours: "平日 9:00〜12:00・13:00〜16:30（指定道路図の閲覧の時間）",
  note: PREF_NOTE,
  noPhoneInquiry: true,
});

/** 県のトップページ（県はリンクを原則トップページへと求めている。個別のページへは、担当課と相談してから） */
const PREF_TOP = "https://www.pref.hiroshima.lg.jp/";

/** 県の指定道路図（参考図）。市町ごとのページ（最初に「ご利用上の注意」。同意して進むと図が出る）へは、県のトップページから進む */
const prefMap = (name: string): MapLink => ({
  kind: "designated_only",
  label: `広島県 指定道路図（参考図。${name}。県が調べ終えた4号・5号・2項）※広島県のトップページから進む`,
  build: null,
  url: PREF_TOP,
  verified: true,
  tip: `広島県のトップページが開く（県がリンクを原則トップページへと求めているため）。「組織で探す」→ 土木建築局の「建築課」→「指定道路に関すること」の「建築基準法に規定する『指定道路図』の公開について」→「${name}」の順に進む。「ご利用上の注意」を読み、自分で同意して進む（MICHILU は同意の先を開いていない）。県が調べ終えた4号・5号（位置指定道路）・2項道路の大まかな位置と種類の参考図で、建築基準法施行規則の「指定道路図」そのものではない。43条（敷地と道路の関係）を判断する資料・土地の境界を判断する資料・不動産取引のための資料には使えない（県の注意）。道路の幅員・境界・起点や終点は示さない。調べ終えた道路だけで、随時足される。無断の複写・転載は禁じられている。必ず、建設事務所の建築課の窓口で最新の情報を確かめる。`,
});

/** 県が扱う市町で、県の指定道路図があるところ。whole は都市計画区域が全域の市町 */
const prefTown = (name: string, code: string, office: Office, whole = false): Municipality => ({
  pref,
  name,
  codes: [code],
  coverage: "partial",
  maps: [prefMap(name)],
  contact: desk(office),
  note: `県が扱う市町（建築確認と道路の判定は${SHORT(office)}。県「県内の建築確認申請・省エネ適判の受付窓口について」）。県の指定道路図（参考図）で、県が調べ終えた4号・5号・2項道路の大まかな位置が分かる（同意して進む。1号〜3号は載らない）。ほかの道路・くわしいことは建設事務所の建築課の窓口で確かめる。${whole ? "" : `${name}の一部は都市計画区域の外（国の令和7年都市計画現況調査の都市別一覧）。`}${name}が出している地図（市町道の地図など）は調べている途中。`,
});

/** 都市計画区域の無い町（国の令和7年都市計画現況調査の都市別一覧に無い。県の指定道路図の市町にも無い） */
const outsideTown = (name: string, code: string, office: Office): Municipality => ({
  pref,
  name,
  codes: [code],
  coverage: "outside",
  maps: [],
  contact: desk(office),
  note: `全域が都市計画区域外（国の令和7年都市計画現況調査の都市別一覧に${name}の都市計画区域は無い）。建築基準法の接道の決まり（43条）は、都市計画区域・準都市計画区域の中でかかる。建築のことは${SHORT(office)}が受け持つ（県「県内の建築確認申請・省エネ適判の受付窓口について」）。`,
});

