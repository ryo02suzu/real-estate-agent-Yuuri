// 市の道路種別のデータを MICHILU の中に表示してよいと確かめた市区町村。
//
// 自治体の公開の地図は、データを外から読める作りでも、利用規約で「無断の複製・転載」「営利目的の利用」を禁じていることが多い
// （2026-11-13 に各サイトの利用規約の全文を読んで確かめた：埼玉県指定道路図「営利目的でサービスを利用すること」「商用転用すること」、
//   つくば市「営利目的で本サイト及びコンテンツを利用すること」、行田市「本図で得られた情報を営利目的で利用することはできません」、
//   日野市「いかなる理由においても著作権者に無断で転載又は複製はできません」、兵庫県指定道路情報「営利目的でサービスを利用すること」、
//   近江八幡市「すべての地図情報の転載は禁じます」。docs/road-data-permission.md）。
// そういう所のデータは、自治体から使ってよいと確かめられるまで、アプリの中には表示しない（公式の地図を物件の位置で開く）。
// 表示してよい根拠（オープンデータのライセンス・自治体からの許可）を確かめたら、市区町村コードでここに足す。
// 足すと、その市の MapLink.read（読み方の設定は data/<県>.ts に残してある）が使われるようになる。

export type RoadReadPermission = {
  /** 表示してよい根拠（ライセンスの名前・許可を受けた日と相手） */
  basis: string;
  /** 画面に出す出典（ライセンスが求める書き方） */
  credit: string;
  /** 根拠を確かめた日 */
  date: string;
};

export const ROAD_READ_PERMITTED: Record<string, RoadReadPermission> = {
  // 柏崎市：市が ArcGIS Online で公開している「位置指定道路」（2020年3月30日時点）・「法第42条2項道路」（2020年5月7日時点）。
  // どちらもアイテムの利用条件に「CC BY 2.1 JP」と書かれている（持ち主 kashiwazaki_admin。2026-11-13 に確認）
  "15205": {
    basis: "柏崎市が公開しているデータの利用条件が CC BY 2.1 JP（表示すれば複製・加工・営利目的の利用ができる）",
    credit: "出典：柏崎市「位置指定道路」「法第42条2項道路」（CC BY 2.1 JP）を MICHILU が表示",
    date: "2026-11-13",
  },
};

/** その市区町村（コードのどれか）の道路種別のデータを、アプリの中に表示してよいか。よければ根拠と出典 */
export function roadReadPermission(codes: string[]): RoadReadPermission | undefined {
  for (const c of codes) if (ROAD_READ_PERMITTED[c]) return ROAD_READ_PERMITTED[c];
  return undefined;
}
