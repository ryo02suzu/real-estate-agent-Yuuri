// 市区町村コード（国土地理院の逆ジオコーダの muniCd）の扱い

// 政令市（全国の20市）の市のコード。小さい順に並べる。区のコードは、頭3桁が同じ市のコードのうち、区のコード以下で最も大きいものの区
// （静岡 22100・浜松 22130、大阪 27100・堺 27140、北九州 40100・福岡 40130、横浜 14100・川崎 14130・相模原 14150 は頭3桁が同じ）。
// 東京の特別区（131xx）は、市のコードが無いのでそのまま
const DESIGNATED = [
  "01100", // 札幌市
  "04100", // 仙台市
  "11100", // さいたま市
  "12100", // 千葉市
  "14100", // 横浜市
  "14130", // 川崎市
  "14150", // 相模原市
  "15100", // 新潟市
  "22100", // 静岡市
  "22130", // 浜松市
  "23100", // 名古屋市
  "26100", // 京都市
  "27100", // 大阪市
  "27140", // 堺市
  "28100", // 神戸市
  "33100", // 岡山市
  "34100", // 広島市
  "40100", // 北九州市
  "40130", // 福岡市
  "43100", // 熊本市
];

/** 政令市の区のコード（14131 など）→ 市のコード（14130）。政令市でなければそのまま。国の一覧の多くは政令市を市で1つにしている */
export function cityCode(muniCd: string): string {
  return DESIGNATED.filter((d) => d.slice(0, 3) === muniCd.slice(0, 3) && d <= muniCd).pop() ?? muniCd;
}
