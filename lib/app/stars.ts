/** 日心の黄道座標（au、J2000 の黄道） */
export function heliocentric(name: keyof typeof ELEMENTS, at: Date): Vec3 {
  const T = (julianDay(at) - 2451545.0) / 36525;
  const [e0, e1] = ELEMENTS[name];
  const [a, e, I, L, wbar, O] = e0.map((v, i) => v + e1[i] * T);
  const w = wbar - O;
  let M = (((L - wbar) % 360) + 540) % 360 - 180;
  M *= R;
  let E = M + e * Math.sin(M);
  for (let i = 0; i < 8; i++) {
    const dE = (M - (E - e * Math.sin(E))) / (1 - e * Math.cos(E));
    E += dE;
    if (Math.abs(dE) < 1e-8) break;
  }
  const xp = a * (Math.cos(E) - e), yp = a * Math.sqrt(1 - e * e) * Math.sin(E);
  const cw = Math.cos(w * R), sw = Math.sin(w * R), cO = Math.cos(O * R), sO = Math.sin(O * R), cI = Math.cos(I * R), sI = Math.sin(I * R);
  return [
    (cw * cO - sw * sO * cI) * xp + (-sw * cO - cw * sO * cI) * yp,
    (cw * sO + sw * cO * cI) * xp + (-sw * sO + cw * cO * cI) * yp,
    sw * sI * xp + cw * sI * yp,
  ];
}

const OBLIQ = 23.43928 * R;
/** 地心の黄道座標（au、J2000）→ 赤経・赤緯（度、その日の分点） */
function equatorial(v: Vec3, at: Date): [number, number] {
  const x = v[0], y = Math.cos(OBLIQ) * v[1] - Math.sin(OBLIQ) * v[2], z = Math.sin(OBLIQ) * v[1] + Math.cos(OBLIQ) * v[2];
  const ra = ((Math.atan2(y, x) / R) % 360 + 360) % 360;
  const dec = Math.atan2(z, Math.hypot(x, y)) / R;
  return precess(ra, dec, at);
}

export type Planet = { name: string; label: string; ra: number; dec: number; mag: number; bv: number };

/** 太陽の赤経・赤緯（度） */
export function sunRaDec(at: Date): [number, number] {
  const e = heliocentric("earth", at);
  return equatorial([-e[0], -e[1], -e[2]], at);
}

/** 惑星の赤経・赤緯と実視等級（距離と位相角から。土星の環は含まない） */
export function planets(at: Date): Planet[] {
  const earth = heliocentric("earth", at);
  const out: Planet[] = [];
  const list: [keyof typeof ELEMENTS, string, number, (r: number, D: number, ph: number) => number][] = [
    ["mercury", "水星", 0.9, (r, D, ph) => -0.42 + 5 * Math.log10(r * D) + 0.038 * ph - 0.000273 * ph * ph + 2e-6 * ph * ph * ph],
    ["venus", "金星", 0.8, (r, D, ph) => -4.4 + 5 * Math.log10(r * D) + 0.0009 * ph + 0.000239 * ph * ph - 6.5e-7 * ph * ph * ph],
    ["mars", "火星", 1.4, (r, D, ph) => -1.52 + 5 * Math.log10(r * D) + 0.016 * ph],
    ["jupiter", "木星", 0.8, (r, D, ph) => -9.4 + 5 * Math.log10(r * D) + 0.005 * ph],
    ["saturn", "土星", 1.0, (r, D, ph) => -8.88 + 5 * Math.log10(r * D) + 0.044 * ph],
  ];
  for (const [key, label, bv, magOf] of list) {
    const p = heliocentric(key, at);
    const g: Vec3 = [p[0] - earth[0], p[1] - earth[1], p[2] - earth[2]];
    const r = Math.hypot(p[0], p[1], p[2]), D = Math.hypot(g[0], g[1], g[2]), s = Math.hypot(earth[0], earth[1], earth[2]);
    // 位相角（太陽−惑星−地球）
    const cosPh = Math.max(-1, Math.min(1, (r * r + D * D - s * s) / (2 * r * D)));
    const ph = Math.acos(cosPh) / R;
    const [ra, dec] = equatorial(g, at);
    out.push({ name: key, label, ra, dec, mag: Math.round(magOf(r, D, ph) * 100) / 100, bv });
  }
  return out;
}

export type SkyObject = { label: string; alt: number; az: number; mag: number; bv: number; planet: boolean; airmass: number };

/**
 * いま見える明るい星と惑星（高度 −1° より上、見かけの等級 3.2 まで。大気の減光で地平線の近くは暗い）。
 * 等級は減光後。lat・lon は度（東京駅の基準）
 */
export function skyObjects(at: Date, lat: number, lon: number): SkyObject[] {
  const out: SkyObject[] = [];
  const push = (label: string, raDeg: number, decDeg: number, mag: number, bv: number, planet: boolean) => {
    const { alt, az } = altAz(raDeg, decDeg, at, lat, lon);
    if (alt < -1) return;
    // 大気の減光（街の空気：天頂で 0.3 等、空気量は Kasten の式）
    const z = Math.max(0, 90 - alt);
    const airmass = 1 / (Math.cos(z * R) + 0.50572 * Math.pow(96.07995 - z, -1.6364));
    const m = mag + 0.3 * airmass;
    if (m > 3.2) return;
    out.push({ label, alt, az, mag: Math.round(m * 100) / 100, bv, planet, airmass: Math.round(airmass * 100) / 100 });
  };
  for (const [name, raH, dec, mag, bv] of STARS) {
    const [ra, de] = precess(raH * 15, dec, at);
    push(name, ra, de, mag, bv, false);
  }
  for (const p of planets(at)) push(p.label, p.ra, p.dec, p.mag, p.bv, true);
  return out;
}

/** 色指数 B−V → 画面の色（青白〜白〜橙。輝度 1 に正規化していない） */
export function starColor(bv: number): Vec3 {
  const t = Math.max(-0.35, Math.min(1.8, bv));
  if (t < 0) return [0.72 + 0.8 * t, 0.84 + 0.45 * t, 1.0];
  if (t < 0.6) return [1.0, 1.0 - 0.12 * (t / 0.6), 1.0 - 0.3 * (t / 0.6)];
  return [1.0, 0.88 - 0.25 * ((t - 0.6) / 1.2), 0.7 - 0.3 * ((t - 0.6) / 1.2)];
}

/**
 * 見える度合い（0〜1）：太陽の高度から。明るいものほど早く見える（金星は日没の直後、0 等は太陽 −8°、2 等は −13° でいっぱいに）。
 * 空の明るさそのものでの消え方は描く側（空の輝度から）
 */
export function starVisibility(mag: number, sunAltitude: number): number {
  const thr = Math.min(-1, Math.max(-13, -5 - 2.3 * mag));
  const t = Math.min(1, Math.max(0, (sunAltitude - thr) / -3));
  return t * t * (3 - 2 * t);
}

/**
 * 画面での見え方：点の明るさ（出力の色に足す値。1 を超えると中心が白く飛ぶ＝写真の明るい星）、点の大きさ（pt。明るいほど大きい）、
 * またたきの大きさ（低い星ほど空気の揺らぎで大きくまたたく。惑星は面があるのでほとんどまたたかない）
 */
export function starLook(o: SkyObject): { intensity: number; size: number; twinkle: number } {
  return {
    // 写真の階調に合わせて等級の差を少し縮める（0.35/等。1 等は中心が白に近く、3 等は背景より少し明るいだけ）
    intensity: Math.min(1.6, Math.pow(10, -0.35 * (o.mag - 0.3))),
    size: 2.2 + 1.3 * Math.max(0, 1 - o.mag),
    twinkle: o.planet ? 0.04 : 0.12 + 0.35 * Math.min(1, Math.max(0, (o.airmass - 1) / 3)),
  };
}
