const R = Math.PI / 180;

/** ユリウス日 */
export const julianDay = (at: Date) => at.getTime() / 86400000 + 2440587.5;

/** グリニッジ恒星時（度） */
export function gmstDeg(at: Date): number {
  const D = julianDay(at) - 2451545.0;
  return (((280.46061837 + 360.98564736629 * D) % 360) + 360) % 360;
}

/** 赤経（度）・赤緯（度）→ 高度（度）・方位（度、北 0・東 90）。大気の屈折で地平線の近くは少し持ち上がる */
export function altAz(raDeg: number, decDeg: number, at: Date, lat: number, lon: number): { alt: number; az: number } {
  const ha = (gmstDeg(at) + lon - raDeg) * R;
  const phi = lat * R;
  const dec = decDeg * R;
  const sinAlt = Math.sin(phi) * Math.sin(dec) + Math.cos(phi) * Math.cos(dec) * Math.cos(ha);
  let alt = Math.asin(Math.max(-1, Math.min(1, sinAlt))) / R;
  const y = -Math.sin(ha) * Math.cos(dec);
  const x = Math.sin(dec) * Math.cos(phi) - Math.cos(dec) * Math.sin(phi) * Math.cos(ha);
  const az = ((Math.atan2(y, x) / R) % 360 + 360) % 360;
  // 屈折（Sæmundsson の式。度）。地平線で 0.5° ほど
  if (alt > -2) alt += 1.02 / Math.tan((alt + 10.3 / (alt + 5.11)) * R) / 60;
  return { alt, az };
}

/** J2000 の赤経・赤緯（度）に歳差を足す（年あたり 赤経 +0.01281°＋…、赤緯 +0.00557°×cos α） */
export function precess(raDeg: number, decDeg: number, at: Date): [number, number] {
  const t = (julianDay(at) - 2451545.0) / 365.25;
  const m = 0.012812, n = 0.005567;
  const ra = raDeg * R, dec = decDeg * R;
  return [raDeg + (m + n * Math.sin(ra) * Math.tan(dec)) * t, decDeg + n * Math.cos(ra) * t];
}

